package net.valdora.warps;

public class Warp {
    public String id;
    public String world;
    public double x;
    public double y;
    public double z;
    public float yaw;
    public float pitch;
    
    public Warp() {
        id = "";
        world = "";
        x = 0.0;
        y = 0.0;
        z = 0.0;
        yaw = 0.0f;
        pitch = 0.0f;
    }
}
